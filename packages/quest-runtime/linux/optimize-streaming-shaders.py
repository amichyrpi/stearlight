def optimize(runtime):
    directory = runtime / "resources/shaders/vulkan"
    for name, (original_hash, optimized_hash, edits) in PATCHES.items():
        path = directory / name
        if not path.is_file():
            continue
        shader = path.read_bytes()
        if hashlib.sha256(shader).hexdigest() != original_hash:
            continue
        result = bytearray(shader)
        for start, end, replacement in reversed(edits):
            result[start * 4:end * 4] = bytes.fromhex(replacement)
        if hashlib.sha256(result).hexdigest() != optimized_hash:
            raise ValueError(f"Invalid streaming shader patch: {name}")
        temporary = path.with_suffix(".stearlight-new")
        temporary.write_bytes(result)
        temporary.chmod(path.stat().st_mode & 0o777)
        temporary.replace(path)


if __name__ == "__main__":
    optimize(Path(sys.argv[1]))
